"""Single source of truth for the exp2 and reciprocal ROMs.

fixed.py imports exp2_lut()/recip_lut() from here; running this file writes the same values to
rtl/lut_pkg.sv as packed SystemVerilog localparams (no $readmemh, so it works in Verilator, Yosys and
WASM without any file access). test_golden.py fails if the checked-in file drifts.

    python sim/golden/gen_luts.py
"""

from pathlib import Path

PKG_PATH = Path(__file__).resolve().parents[2] / "rtl" / "lut_pkg.sv"

EXP2_FRAC_BITS = 8  # LUT256: index = fractional part of the Q9.8 argument
EXP2_OUT_FRAC = 15  # entries are UQ1.15
RECIP_IDX_BITS = 6  # LUT64: index = top 6 fraction bits of the normalized mantissa
RECIP_OUT_FRAC = 16  # entries are UQ0.16


def exp2_lut() -> list[int]:
    """LUT[f] = round(2**15 * 2**(f/256)) for f in 0..255. Range 32768..65358, so 16 bits."""
    return [round((1 << EXP2_OUT_FRAC) * 2 ** (f / (1 << EXP2_FRAC_BITS))) for f in range(1 << EXP2_FRAC_BITS)]


def recip_lut() -> list[int]:
    """LUT[i] = round(2**16 / (1 + (i + 0.5) / 64)): seed for 1/M, M in [1, 2). Range 32897..65028, 16 bits."""
    n = 1 << RECIP_IDX_BITS
    return [round((1 << RECIP_OUT_FRAC) / (1 + (i + 0.5) / n)) for i in range(n)]


def _array(name: str, values: list[int]) -> str:
    """Packed constant: entry i is bits [16*i +: 16]. Unpacked array localparams do not parse in Yosys."""
    n = len(values)
    tokens = [f"16'h{v:04x}" for v in reversed(values)]  # the first entry goes in the low bits
    rows = []
    for i in range(0, n, 8):
        rows.append("        " + ", ".join(tokens[i:i + 8]))
    body = ",\n".join(rows)
    return f"    localparam logic [{16 * n - 1}:0] {name} = {{\n{body}\n    }};\n"


def render_pkg() -> str:
    return (
        "// GENERATED by sim/golden/gen_luts.py. Do not edit; run the script and commit the result.\n"
        "/* verilator lint_off UNUSEDPARAM */  // each module uses one of the two tables\n"
        "package lut_pkg;\n"
        "    // exp2: round(2^15 * 2^(f/256)), UQ1.15\n"
        + _array("EXP2_LUT", exp2_lut())
        + "    // reciprocal seed: round(2^16 / (1 + (i + 0.5) / 64)), UQ0.16\n"
        + _array("RECIP_LUT", recip_lut())
        + "endpackage\n"
    )


def write_all() -> None:
    PKG_PATH.write_text(render_pkg())


if __name__ == "__main__":
    write_all()
    print(f"wrote {PKG_PATH} (EXP2_LUT[256], RECIP_LUT[64], packed)")
