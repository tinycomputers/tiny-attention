"""Export data the web app and its tests share with the golden model.

- web/src/lib/presets.ts: the attention presets (presets.py), float Q/K/V with labels.
- wasm/fixtures/quantize_cases.json: float inputs and the quantized values and cfg_scale that fixed.quantize produces.
    python sim/golden/export_web_data.py
"""

import json
import re
from pathlib import Path

import numpy as np

import fixed
import presets
from float_ref import attention
from traffic import traffic
from export_fixtures import ROOT

WEB_PRESETS = ROOT / "web" / "src" / "lib" / "presets.ts"
QUANT_CASES = ROOT / "wasm" / "fixtures" / "quantize_cases.json"
TRAFFIC_TS = ROOT / "web" / "src" / "lib" / "traffic-table.ts"
MEASURED_TS = ROOT / "web" / "src" / "lib" / "measured.ts"
STUDY_TXT = Path(__file__).resolve().parent / "study_results_1000seeds.txt"
PERF_JSON = ROOT / "sim" / "perf_baseline.json"


def r(x):
    return round(float(x), 6)


def preset_entries():
    out = []
    for make in presets.ALL:
        p = make()
        out.append(dict(
            name=p["name"],
            labels=list(p["labels"]),
            causal=bool(p["causal"]),
            q=[[r(x) for x in row] for row in p["q"]],
            k=[[r(x) for x in row] for row in p["k"]],
            v=[[r(x) for x in row] for row in p["v"]],
        ))
    return out


def presets_ts(entries):
    body = json.dumps(entries, indent=1)
    return ("// GENERATED by sim/golden/export_web_data.py from sim/golden/presets.py. Do not edit.\n"
            "export interface Preset {\n"
            "  name: string;\n"
            "  labels: string[];\n"
            "  causal: boolean;\n"
            "  q: number[][];\n"
            "  k: number[][];\n"
            "  v: number[][];\n"
            "}\n\n"
            f"export const PRESETS: Preset[] = {body};\n")


def quant_cases():
    rng = np.random.default_rng(61)
    cases = []
    for amp in (0.5, 2.5, 3.5):
        n = 8
        qf, kf, vf = (np.round(rng.normal(0, amp, (n, 4)), 6) for _ in range(3))  # what the web app will see
        z = fixed.quantize(qf, kf, vf)
        cases.append(dict(
            q=[[r(x) for x in row] for row in qf],
            k=[[r(x) for x in row] for row in kf],
            v=[[r(x) for x in row] for row in vf],
            expQ=z.q.reshape(-1).tolist(),
            expK=z.k.reshape(-1).tolist(),
            expV=z.v.reshape(-1).tolist(),
            expCfgScale=int(z.cfg_scale),
        ))
    # an all-zero tensor: scale falls back to 1.0
    z0 = np.zeros((4, 4))
    z = fixed.quantize(z0, z0, z0)
    cases.append(dict(q=z0.tolist(), k=z0.tolist(), v=z0.tolist(),
                      expQ=z.q.reshape(-1).tolist(), expK=z.k.reshape(-1).tolist(),
                      expV=z.v.reshape(-1).tolist(), expCfgScale=int(z.cfg_scale)))
    return cases


def traffic_entries():
    """Expected HBM bytes and tile counts for every (schedule, N, causal, Q block rows) the web app can run."""
    out = {}
    for n in range(4, 33, 4):
        for causal in (False, True):
            for qrows in (4, 8, 16, 32):
                if qrows > n:
                    continue
                t = traffic(n, causal, "FLASH", qblock=qrows)
                out[f"FLASH:{n}:{int(causal)}:{qrows}"] = dict(rd=t["rd"], wr=t["wr"], tiles=t["tiles"])
            t = traffic(n, causal, "NAIVE", qblock=4)
            out[f"NAIVE:{n}:{int(causal)}:4"] = dict(rd=t["rd"], wr=t["wr"], tiles=t["tiles"])
    return out


def traffic_ts(entries):
    body = json.dumps(entries, indent=1, sort_keys=True)
    return ("// GENERATED by sim/golden/export_web_data.py from sim/golden/traffic.py. Do not edit.\n"
            "// Key: `${mode}:${n}:${causal ? 1 : 0}:${qrows}`. rd / wr: HBM bytes; tiles: tile count.\n"
            "export interface TrafficEntry {\n  rd: number;\n  wr: number;\n  tiles: number;\n}\n\n"
            f"export const TRAFFIC: Record<string, TrafficEntry> = {body};\n")


STUDY_SEQ = re.compile(
    r"N=\s*(\d+) causal=(\d) flash\s+dp max\s+([\d.]+) mean\s+([\d.]+) \| tot max\s+([\d.]+) mean\s+([\d.]+)")
STUDY_VS = re.compile(
    r"^(flash|naive) N=32\s+dp max\s+([\d.]+) mean\s+([\d.]+) \| tot max\s+([\d.]+) mean\s+([\d.]+)", re.M)


def study_numbers():
    """Rows of the recorded 1000-seed study (sim/golden/study_results_1000seeds.txt), parsed verbatim."""
    text = STUDY_TXT.read_text()
    seq = []
    for m in STUDY_SEQ.finditer(text):
        n, c, dpm, dpa, tm, ta = m.groups()
        seq.append(dict(n=int(n), causal=c == "1", dpMax=float(dpm), dpMean=float(dpa), totMax=float(tm), totMean=float(ta)))
    vs = {}
    for m in STUDY_VS.finditer(text):
        mode, dpm, dpa, tm, ta = m.groups()
        vs[mode] = dict(dpMax=float(dpm), dpMean=float(dpa), totMax=float(tm), totMean=float(ta))
    return dict(sequence=seq, flashVsNaive=vs, raw=text)


PERF_KEYS = [
    ("FLASH, Q block 4 rows, no overlap", "flash/N32/c0/q4/o0/L10"),
    ("FLASH, Q block 4 rows, overlap", "flash/N32/c0/q4/o1/L10"),
    ("FLASH, Q block 16 rows, no overlap", "flash/N32/c0/q16/o0/L10"),
    ("FLASH, Q block 16 rows, overlap", "flash/N32/c0/q16/o1/L10"),
    ("NAIVE", "naive/N32/c0/L10"),
]


def perf_numbers():
    base = json.loads(PERF_JSON.read_text())
    return [dict(label=label, cycles=base[key]) for label, key in PERF_KEYS]


def preset_errors():
    """Max |engine - float| per preset, in float units, on the golden model (the same numbers the visualizer shows)."""
    out = []
    for make in presets.ALL:
        p = make()
        q, k, v = (np.round(np.asarray(p[x], dtype=np.float64), 6) for x in ("q", "k", "v"))
        n = q.shape[0]
        qz = fixed.quantize(q, k, v)
        res = fixed.flash(qz, n, p["causal"], qblock=min(4, n))
        out_f = fixed.dequant_out(res, qz)
        ref, _ = attention(q, k, v, p["causal"])
        out.append(dict(name=p["name"], n=n, causal=bool(p["causal"]), maxErr=float(np.max(np.abs(out_f - ref)))))
    return out


def measured_ts():
    study = study_numbers()
    body = dict(study=dict(sequence=study["sequence"], flashVsNaive=study["flashVsNaive"]),
                studyRaw=study["raw"], perfN32=perf_numbers(), presetErrors=preset_errors())
    return ("// GENERATED by sim/golden/export_web_data.py from the golden model, sim/golden/study_results_1000seeds.txt\n"
            "// and sim/perf_baseline.json. Do not edit.\n"
            "export const MEASURED = " + json.dumps(body, indent=1) + " as const;\n")


def main():
    WEB_PRESETS.write_text(presets_ts(preset_entries()))
    QUANT_CASES.write_text(json.dumps(quant_cases()) + "\n")
    TRAFFIC_TS.write_text(traffic_ts(traffic_entries()))
    MEASURED_TS.write_text(measured_ts())
    print(f"wrote {WEB_PRESETS.name} ({len(presets.ALL)} presets), {QUANT_CASES.name}, {TRAFFIC_TS.name}, {MEASURED_TS.name}")


if __name__ == "__main__":
    main()
